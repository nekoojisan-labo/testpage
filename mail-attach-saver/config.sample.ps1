#requires -Version 5.1
<#
    config.sample.ps1

    設定サンプル（全項目にコメントつき）。
    このファイルをコピーして config.local.ps1 を作成し、現地の実際の値を設定する。

    config.local.ps1 は Git 管理対象外（.gitignore 参照）。
    実値（保存先パス等）は現地でしか分からないため、このリポジトリ上の
    config.local.ps1 はプレースホルダのままコミットされている。

    Save-MailAttachments.ps1 からは次のように読み込む:
        . (Join-Path $PSScriptRoot "config.local.ps1")
#>

# --------------------------------------------------------------------------
# 添付ファイルの保存先ルートフォルダ
# 共有ドライブ上の実在するパスに置き換えること。末尾に \ は付けない。
# 例: "Z:\<保存先ルートのパス>"
# --------------------------------------------------------------------------
$SaveRoot = "Z:\<保存先ルートのパスをここに設定>"

# --------------------------------------------------------------------------
# 遡及日数: 受信トレイの「何日前まで」を処理対象にするか
# Items.Restrict で ReceivedTime を絞り込み、受信トレイ全件走査を避けるために使う。
# 初回導入時はここを大きめにして -Backfill 実行し、以降は既定値に戻す運用を想定。
# --------------------------------------------------------------------------
$RetentionDays = 90

# --------------------------------------------------------------------------
# 件名検知パターン（正規表現の配列。大文字小文字は無視して部分一致で判定する）
# 既定: DJ / BJ / CH + 数字ちょうど5桁（6桁以上の数字列は誤検知しないよう
# (?!\d) で除外している）。追加パターンが必要な場合は配列に足すだけでよい。
# 例: @('(DJ|BJ|CH)\d{5}(?!\d)', 'XY\d{4}(?!\d)')
# --------------------------------------------------------------------------
$SubjectPatterns = @(
    '(DJ|BJ|CH)\d{5}(?!\d)'
)

# --------------------------------------------------------------------------
# インライン画像（署名画像等）を保存対象から除外するか
# $true: PR_ATTACHMENT_HIDDEN / cid: 参照で判定し、該当する添付は保存しない
# $false: 除外判定を行わず、全添付を保存する
# --------------------------------------------------------------------------
$ExcludeInlineImages = $true

# --------------------------------------------------------------------------
# 1回の実行で処理するメール数の上限（古い受信順に処理する）
# 前回試作で635通を一括処理し想定外の大量フォルダが作成された事故の再発防止策。
# -Backfill スイッチ指定時のみこの上限を無視して全件処理する。
# --------------------------------------------------------------------------
$MaxMailsPerRun = 50

# --------------------------------------------------------------------------
# 保存完了時にポップアップ通知を出すかどうか
# $true:  1件以上保存した実行のみ、手動で閉じるまで消えないポップアップを表示
# $false: 通知を出さない（ログのみ）
# --------------------------------------------------------------------------
$EnableNotification = $true

# --------------------------------------------------------------------------
# 処理済みメールのEntryIDを記録するファイル（重複防止の主軸）
# 通常は変更不要。$PSScriptRoot はこの設定ファイルが置かれたフォルダを指す。
# --------------------------------------------------------------------------
$ProcessedIdsPath = Join-Path $PSScriptRoot "logs\processed-ids.txt"

# --------------------------------------------------------------------------
# 実行ログの保存先フォルダ（ファイル名は run-YYYYMM.log の形式で自動生成される）
# 通常は変更不要。
# --------------------------------------------------------------------------
$LogFolder = Join-Path $PSScriptRoot "logs"
