#requires -Version 5.1
<#
    config.sample.ps1  (mail-watch)

    設定サンプル（全項目コメント付き）。
    このファイルをコピーして config.local.ps1 を作成し、実際のドメイン等を設定する。

    config.local.ps1 は Git 管理対象外（.gitignore 参照）。
    ドメインの実値は本人（開発者）しか分からないため、このリポジトリ上の
    config.local.ps1 はプレースホルダのままにしてある。

    Watch-ClientMail.ps1 からは次のように読み込む:
        . (Join-Path $PSScriptRoot "config.local.ps1")
#>

# --------------------------------------------------------------------------
# 監視対象の差出人ドメイン（"@"より後ろの部分。複数可）
# 例: "example.co.jp" と設定すると、
#     user@example.co.jp はもちろん user@mail.example.co.jp のようなサブドメインからの
#     メールも監視対象になる（後方一致 "@ドメイン" または ".ドメイン" で判定するため）。
# --------------------------------------------------------------------------
$WatchSenderDomains = @("<相手ドメイン例: example.co.jp>")

# --------------------------------------------------------------------------
# 保存対象の添付が1件以上あることを候補の条件にするか
# $true（既定・確定仕様）: 添付なしメール（挨拶メール等）は無視する
# $false: ドメイン一致だけで候補にする（添付があれば保存し、無ければ記録のみ）
# --------------------------------------------------------------------------
$RequireAttachment = $true

# --------------------------------------------------------------------------
# 遡及日数: 受信トレイの「何日前まで」を処理対象にするか
# --------------------------------------------------------------------------
$RetentionDays = 7

# --------------------------------------------------------------------------
# 1回の実行で処理する候補メール数の上限（古い受信順）
# ドメイン不一致・添付なしのメールは上限に関係なく評価される
# （kitと同じ「候補にのみ上限を適用する」設計。詳細はREADME.md参照）
# --------------------------------------------------------------------------
$MaxMailsPerRun = 20

# --------------------------------------------------------------------------
# 保存完了時にポップアップ通知を出すか
# --------------------------------------------------------------------------
$EnableNotification = $true

# --------------------------------------------------------------------------
# 添付の保存先ルートフォルダ（既定はこのツール自身のフォルダ直下の received\）
# --------------------------------------------------------------------------
$SaveRoot = Join-Path $PSScriptRoot "received"

# --------------------------------------------------------------------------
# 着信記録(JSONL)の保存先。Claudeが後で読む想定のファイル。
# 1メール=1行・UTF-8（BOM無し）で追記される。
# --------------------------------------------------------------------------
$EventLogPath = Join-Path $PSScriptRoot "logs\inbox-events.jsonl"

# --------------------------------------------------------------------------
# 処理済みメールのEntryIDを記録するファイル（通常は変更不要）
# --------------------------------------------------------------------------
$ProcessedIdsPath = Join-Path $PSScriptRoot "logs\processed-ids.txt"

# --------------------------------------------------------------------------
# 実行ログの保存先フォルダ（通常は変更不要）
# --------------------------------------------------------------------------
$LogFolder = Join-Path $PSScriptRoot "logs"
